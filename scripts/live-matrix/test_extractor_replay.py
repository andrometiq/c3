def read_json(path):
    return json.loads(path.read_text())


def events(observation, milestone):
    return [event for event in observation['events'] if event['milestone'] == milestone]


def semantic(observation):
    """Only byte-representation digests differ. Every other field is compared."""
    value = deepcopy(observation)
    for artifact in value['artifacts']:
        artifact['content_digest'] = None
    return value


def fresh_replay(root):
    code = ('import json,sys; from capture_context import load_capture; '
            'r=load_capture(sys.argv[1]); '
            'print(json.dumps({k:r[k] for k in ("inputs","evidence","classifications","diagnostics")}))')
    result = subprocess.run([sys.executable, '-c', code, str(root)], cwd=Path(__file__).parent,
                            text=True, capture_output=True, check=True)
    return json.loads(result.stdout)


