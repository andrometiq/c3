    def assert_bad_identity(self, name, root, replay):
        """Check the bad canonical claim before evaluating its named failure."""
        observation = replay['inputs'][2]
        if name.startswith('occurrence-'):
            claim = read_json(root/'mutation.json')['identity']
            raw = (root/claim['file']).read_text()
            if claim['line'] is not None:
                raw = raw.splitlines()[claim['line']-1]
            if claim['file'].endswith(('.json', '.jsonl')):
                raw = json.loads(raw)
            for key in claim['path']:
                raw = raw[key]
            if claim['contains']:
                self.assertIn(claim['bad'], raw)
            else:
                self.assertEqual(raw, claim['bad'])
            if 'milestone' in claim:
                event = events(observation, claim['milestone'])[0]
                value = event
                for key in claim['canonical_path']:
                    value = value[key]
                self.assertEqual(value, claim['bad'])
                self.assertFalse(event['collection_complete'])
            if 'absent' in claim:
                self.assertFalse(events(observation, claim['absent']))
            diagnostics = [item for item in replay['diagnostics'] if item['code'] ==
                           'delivery evidence identity mismatch: '+claim['field']+' correlation conflict']
            self.assertTrue(diagnostics)
            self.assertTrue(all(item['locator'].startswith('line:') for item in diagnostics))
            self.assertFalse(observation['collection_complete'])
            if name in ('occurrence-channel-attempt', 'occurrence-inbox-attempt'):
                record = json.loads((root/'records.jsonl').read_text().splitlines()[1])
                extracted = classify(record)
                self.assertTrue(extracted['accept'])
                self.assertEqual(extracted['attempt'], claim['bad'])
                binding = next(json.loads(v) for v in (root/'context/attempts.jsonl').read_text().splitlines()
                               if json.loads(v)['artifact_id']=='host-records' and json.loads(v)['line']==2)
                self.assertNotEqual(binding['attempt_id'], extracted['attempt'])
                self.assertEqual(derive(*replay['inputs'])['received']['41001'], 0)
            if name == 'occurrence-persisted-source':
                persisted = events(observation,'row_persisted')
                self.assertEqual([e['members'][0]['source_ids'] for e in persisted],[['41001'],['41002']])
                self.assertEqual(persisted[0]['members'][0]['row_id'],persisted[1]['members'][0]['row_id'])
                self.assertEqual(persisted[0]['members'][0]['revision'],persisted[1]['members'][0]['revision'])
            return
        terminal = events(observation, 'attempt_terminal')
        host = events(observation, 'transcript_recorded')
        receipt = events(observation, 'receipt_accepted')
        reserved = events(observation, 'attempt_reserved')
        if name == 'wrong-terminal-token':
            self.assertEqual(terminal[0]['token'], 'token-terminal-wrong')
            self.assertEqual(terminal[0]['attempt_id'], reserved[0]['attempt_id'])
            self.assertEqual(terminal[0]['group_id'], reserved[0]['group_id'])
            self.assertNotEqual(terminal[0]['token'], reserved[0]['token'])
        elif name == 'wrong-host-session':
            self.assertEqual(host[0]['scope']['host_session_id'], 'session-host-wrong')
            self.assertNotEqual(host[0]['scope']['host_session_id'], replay['inputs'][0]['host_session_id'])
            self.assertEqual(derive(*replay['inputs'])['received']['41001'], 0)
        elif name == 'misattributed-transcript':
            self.assertTrue(any('ownership conflict' in item['code'] for item in replay['diagnostics']))
            self.assertEqual(next(stream for stream in observation['streams'] if stream['id']=='host')['scope']['host_session_id'], 'session-host-wrong')
            self.assertEqual(host[0]['scope']['host_session_id'], 'session-host-original')
        elif name in ('wrong-broker-session', 'reused-pid-different-epoch', 'wrong-terminal-epoch'):
            observed = terminal[0] if name == 'wrong-terminal-epoch' else receipt[0]
            key, expected = ('session_id','session-broker-wrong') if name=='wrong-broker-session' else ('connection_epoch_id','epoch-other')
            self.assertEqual(observed['scope'][key], expected)
            self.assertNotEqual(observed['scope'][key], reserved[0]['scope'][key])
            if name=='reused-pid-different-epoch':
                owners=read_json(root/'context/ownership.json')['owners']
                self.assertEqual({row['pid'] for row in owners},{45671})
        elif name=='duplicate-host-delivery':
            copies=[event for event in host if event['members'][0]['source_ids']==['41001']]
            self.assertEqual(len(copies),2)
            self.assertEqual(len({event['delivery_id'] for event in copies}),2)
            self.assertEqual(len({event['payload']['host_record_id'] for event in copies}),2)
        elif name=='duplicate-source-replacing-another':
            self.assertEqual([event['members'][0]['source_ids'] for event in host],[['41001'],['41001']])
            self.assertEqual([event['members'][0]['row_id'] for event in host],['row-original-1','row-original-2'])
            self.assertEqual((root/'records.jsonl').read_text().count('MATRIX_SAMPLE'),2)
        elif name=='stale-retired-revision':
            self.assertEqual(terminal[0]['payload']['retired_members'][0]['revision']['value'],'a'*64)
            persisted=events(observation,'row_persisted')[-1]
            self.assertEqual(persisted['members'][0]['revision']['value'],'c'*64)
            self.assertLess(persisted['position']['time_ms'],terminal[0]['position']['time_ms'])
        elif name=='wrong-retired-row':
            self.assertEqual(terminal[0]['payload']['retired_members'][0]['row_id'],'row-other')
            self.assertNotEqual(terminal[0]['payload']['retired_members'][0]['row_id'],reserved[0]['members'][0]['row_id'])
            self.assertEqual(len(terminal[0]['payload']['retired_members']),len(reserved[0]['members']))
        elif name in ('wrong-recorded-fetch-token','wrong-held-response-token','wrong-recorded-fetch-row','stale-host-revision','duplicate-fetch-row'):
            produced=events(observation,'fetch_result_produced')
            raw_host=[json.loads(line) for line in (root/'records.jsonl').read_text().splitlines()][2]
            candidate=fetch_trailer(result_text(raw_host['message']['content'][0]['content']))
            self.assertFalse(events(observation,'fetch_result_recorded'))
            self.assertTrue(any(item['code']=='fetch candidate rejected' for item in replay['diagnostics']))
            if name=='wrong-held-response-token':
                self.assertEqual(produced[0]['token'],'token-held-wrong')
                self.assertNotEqual(produced[0]['token'],reserved[0]['token'])
                self.assertNotEqual(candidate['token'],produced[0]['token'])
                self.assertTrue(any(item['code']=='held response reservation correlation rejected' for item in replay['diagnostics']))
            elif name=='wrong-recorded-fetch-token':
                self.assertEqual(candidate['token'],'token-recorded-wrong')
                self.assertNotEqual(candidate['token'],produced[0]['token'])
            elif name=='wrong-recorded-fetch-row':
                self.assertEqual(candidate['members'][0]['record_id'],'row-recorded-wrong')
                self.assertNotEqual(candidate['members'][0]['record_id'],produced[0]['members'][0]['row_id'])
            elif name=='stale-host-revision':
                self.assertEqual(candidate['members'][0]['revision'],'c'*64)
                self.assertNotEqual(candidate['members'][0]['revision'],produced[0]['members'][0]['revision']['value'])
            else:
                self.assertIsNone(candidate)

    def test_frozen_three_paths(self):
        roots = sorted(ROOT.glob('healthy-*')) + sorted((ROOT/'mutations').iterdir())
        self.assertGreaterEqual(len(roots), 45)
        for root in roots:
            with self.subTest(capture=root.name):
                replay = load_capture(root)
                self.assert_bad_identity(root.name,root,replay)
                expected_observation=read_json(root/'expected-observation.json')
                expected_result=read_json(root/'expected-result.json')
                self.assertEqual(replay['inputs'][2],expected_observation)
                self.assertEqual(replay['diagnostics'],read_json(root/'expected-diagnostics.json'))
                self.assertEqual(replay['classifications'],read_json(root/'expected-classifications.json'))
                raw_result=evaluate(*replay['inputs'])
                self.assertEqual(raw_result,expected_result)
                self.assertEqual(replay['inputs'][2]['provenance']['kind'],'raw_replay')
                self.assertEqual(replay['inputs'][2]['setup_errors'],[])
                if root.name.startswith('healthy'):
                    self.assertEqual(raw_result,PASS)
                    self.assertTrue(replay['inputs'][2]['collection_complete'])
                else:
                    mutation=read_json(root/'mutation.json')
                    self.assertEqual(raw_result['status'],'FAIL')
                    for reason in mutation['required_reasons']:
                        self.assertIn(reason,raw_result['reasons'])
                    self.assertEqual(replay['inputs'][0],load_capture(ROOT/mutation['base'])['inputs'][0])
                if (root/'mutation.json').exists():
                    mutation=read_json(root/'mutation.json')
                    for change in mutation['changes']:
                        before=(ROOT/mutation['base']/change['file']).read_bytes()
                        after=(root/change['file']).read_bytes() if (root/change['file']).exists() else None
                        self.assertNotEqual(before,after)
                        self.assertEqual(hashlib.sha256(before).hexdigest(),change['before'])
                        self.assertEqual(hashlib.sha256(after).hexdigest() if after is not None else None,change['after'])
                with tempfile.TemporaryDirectory() as directory:
                    exported=export_replay_capture(replay,Path(directory))
                    canonical=read_json(Path(directory)/'verdict-inputs.json')
                    self.assertEqual(evaluate(**canonical),raw_result)
                    exported_diagnostics=exported['diagnostics']
                    exported_classifications=exported['classifications']
                    del exported
                    sanitized=fresh_replay(Path(directory))
                    self.assertEqual(evaluate(*sanitized['inputs']),raw_result)
                    self.assertEqual(sanitized['diagnostics'],exported_diagnostics)
                    self.assertEqual(sanitized['classifications'],exported_classifications)
                    self.assertEqual(sanitized['inputs'][:2],[canonical['scenario'],canonical['contract']])
                    self.assertEqual(semantic(sanitized['inputs'][2]),semantic(canonical['observation']))
                    self.assertEqual(sanitized['evidence'],read_json(Path(directory)/'summary.json'))
                    # Classification locators and outcomes are part of the replay contract.
                    self.assertEqual([(v['locator'],v['accept']) for v in sanitized['classifications']],
                                     [(v['locator'],v['accept']) for v in replay['classifications']])
                    left=derive(**canonical); right=derive(*sanitized['inputs'])
                    self.assertEqual(left,right)

